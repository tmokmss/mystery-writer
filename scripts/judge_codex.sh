#!/usr/bin/env bash
# 問題編と解決編を Codex CLI に渡して編集者として評価させ、最後の応答を <出力.md> に書く。
# 質問は Claude の評価役（サブエージェント）に渡すものと同じ。
# usage: scripts/judge_codex.sh <problem.md> <solution.md> <出力.md>
set -eu
problem=$1
solution=$2
out=$3
mkdir -p "$(dirname "$out")"
prompt="推理小説の編集者として、短編ミステリーを厳しめに評価してください。ファイルやWebは調べず、以下の問題編と解決編だけを読んでください。

前提: 公正さの基準は「探偵が使う手がかりがすべて問題編で読者に見せられているか」「犯人が早く登場しているか」の二点とする。あらゆる別解を作中で消すことは求めない。抜け穴は、この基準に照らして直すべきものとそうでないものを分けること。読者は一般の日本人で、ミステリーを時々読む程度とする。

評価項目:
1. 抜け穴: 解決編の推理が成り立たない読み方、トリックの物理的な無理、犯人が言い逃れできる余地。直すべきもの／直さなくてよいもの に分ける
2. 作中の謎の成立: 作中の警察や住民の立場から見て、この事件は本当に謎として成り立っているか（読者だけがだまされる仕掛けになっていないか、偶然に頼っていないか）
3. 公正さ (1-5)
4. 意外さ (1-5): 一般のミステリー読者が問題編だけで犯人と方法に届く割合の予想（%）と、問題編のどのあたりで犯人に気づきそうかも添える
5. ヒントの量: 犯人を指す描写が多すぎないか。削ってよい描写を具体的に挙げる
6. 読み返したときの納得度 (1-5)
7. 方法と動機の分かりやすさ (1-5): 解決編を読んだ一般の読者が、どう殺したか・なぜ殺したかを一言で説明できるか
8. トリックの面白さ (1-5): 「どうやったか」が明かされたときに絵として浮かび、人に話したくなるか
9. 核の着想: 一読後、この作品の核を一文で言えるか。言えるなら一文で書く
10. 読者が覚えておく必要のある固有の情報（時刻・場所・規則・数値・人物の事実）を列挙し、個数を数える
11. 読みやすさ: 一般の読者に馴染みのない語、何を指すか分かりにくい描写、覚えにくい人名を具体的に挙げる
12. 物語としての力 (1-5)
13. 改善案: 具体的な修正を3つまで。条件を足して別解を消す案より、物語の中で手がかりの効きを良くする案を優先する

回答はMarkdownで、先頭に総評を数行書いてください。項目番号は「## 3. 公正さ: 4」の形の見出しにしてください。

# 問題編
$(cat "$problem")

# 解決編
$(cat "$solution")"
codex exec --skip-git-repo-check -s read-only -o "$out" "$prompt" > "$out.log" 2>&1
rm -f "$out.log"
