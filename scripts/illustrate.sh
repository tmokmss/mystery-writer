#!/usr/bin/env bash
# 最終稿の problem.md・solution.md を Codex CLI に読ませ、挿絵を2〜3枚作らせて同じディレクトリに置き、本文に差し込ませる。
# 画像は PNG で作らせ、横幅1200px の JPEG に縮めて置く（サイトのビルドで WebP に変換される）。
# 参考画像を渡すと画風の見本として Codex に添付する。見本は書籍の挿絵なのでリポジトリに入れず、~/projects/mystery-writer-refs/ に置いている。
# usage: scripts/illustrate.sh <drafts/vN ディレクトリ> [参考画像...]
set -eu
dir=$(cd "$1" && pwd)
shift
refs=()
for f in "$@"; do refs+=(-i "$f"); done
prompt="$dir の problem.md と solution.md は日本語の短編ミステリーです。挿絵を2〜3枚作り、本文に差し込んでください。gitの操作はしないでください。

- 場面の選び方: 一般の読者が文章だけでは思い浮かべにくい場面（場所の様子、人物の位置、核の手がかりになる物の形と置き場所）を選ぶ。問題編の絵は、解決編で明かす真相を描かない・ほのめかさない（文章に書かれている見た目のとおりに描く）。解決編に一枚入れるなら、真相が明かされた後の場面にする。
- 画風: 児童向け小説の章の頭に入る、白黒の素朴な挿絵。物の輪郭は、細いペンか鉛筆の一本線で、少し揺れて途切れる手描きの線にし、形の中は紙の白のまま残す。空、背景、木立や山、影の面は、鉛筆を寝かせて粗くこすった、ざらついた粒の見える灰色で平らに塗りつぶし、白く抜いた形との対比で見せる。形は単純にし、立体感や遠近は弱くてよい。整えたり清書したりしない。人物は簡単な輪郭だけで、顔は描かない（目鼻口を入れない）。手の細部や素材の質感は描き込まない。アニメ調・漫画調にも、写実的にもしない。色は付けない。文字は入れない。横長。画像が添付されていれば、それは画風の見本なので、線と塗りの荒さ・調子をそれに合わせる（見本に描かれている物、構図、人物は使わない）。
- 時代と場所は本文のとおりにする（現代の日本なら、現代の日本の服装・建物・道具にする）。人物の年齢、性別、服装、持ち物は本文と食い違わないようにし、本文に書かれていない目立つ物を足さない。
- 画像生成ツールで作った画像を、このディレクトリに illust1.png, illust2.png … として保存する。
- 保存したら、それぞれ \`sips -s format jpeg -s formatOptions 80 -Z 1200 illustN.png --out illustN.jpg\` で縮め、png は消す。
- problem.md / solution.md の、その場面を描いた段落の直後に、空行で挟んで \`![場面を一言で](illustN.jpg)\` を入れる。本文の文は変えない。
- 最後に、各画像のファイル名、差し込んだ位置（直前の段落の書き出し）、描いた場面、その場面を選んだ理由を報告する。"
codex exec -m gpt-6.2-astra --skip-git-repo-check -s workspace-write -C "$dir" ${refs[@]+"${refs[@]}"} "$prompt"
